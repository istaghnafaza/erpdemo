#!/usr/bin/env node
/**
 * Create Neon branch "staging" + print connection hints.
 * Requires in .env:
 *   NEON_API_KEY=...   (Neon Console → Account → API keys)
 *   NEON_PROJECT_ID=... (Project Settings)
 *
 * Usage: node scripts/setup-neon-staging-branch.mjs
 */
import { readFileSync, existsSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, ".env");

function loadEnv(path) {
  if (!existsSync(path)) return;
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!process.env[key]) process.env[key] = value;
  }
}

loadEnv(envPath);

const apiKey = process.env.NEON_API_KEY?.trim();
const projectId = process.env.NEON_PROJECT_ID?.trim();

if (!apiKey || !projectId) {
  console.error(`
NEON_API_KEY and NEON_PROJECT_ID required in .env

1. Neon Console → Account Settings → API Keys → Create
2. Neon Console → Project SEPS → Settings → copy Project ID
3. Add to .env:
   NEON_API_KEY=...
   NEON_PROJECT_ID=...

Then re-run: node scripts/setup-neon-staging-branch.mjs
`);
  process.exit(1);
}

const headers = {
  Authorization: `Bearer ${apiKey}`,
  Accept: "application/json",
  "Content-Type": "application/json",
};

async function api(path, options = {}) {
  const res = await fetch(`https://console.neon.tech/api/v2${path}`, {
    ...options,
    headers: { ...headers, ...options.headers },
  });
  const text = await res.text();
  let body;
  try {
    body = JSON.parse(text);
  } catch {
    body = { raw: text };
  }
  if (!res.ok) {
    throw new Error(`${options.method ?? "GET"} ${path} → ${res.status}: ${text.slice(0, 500)}`);
  }
  return body;
}

const branchesResp = await api(`/projects/${projectId}/branches`);
const branches = branchesResp.branches ?? [];
const existing = branches.find((b) => b.name === "staging" || b.branch?.name === "staging");

let branchId;
if (existing) {
  branchId = existing.id ?? existing.branch?.id;
  console.log(`Branch "staging" already exists: ${branchId}`);
} else {
  const mainBranch =
    branches.find((b) => b.default) ?? branches.find((b) => b.primary) ?? branches[0];
  const parentId = mainBranch?.id ?? mainBranch?.branch?.id;
  console.log(`Creating branch "staging" from parent ${parentId}...`);
  const created = await api(`/projects/${projectId}/branches`, {
    method: "POST",
    body: JSON.stringify({
      endpoints: [{ type: "read_write" }],
      branch: { name: "staging", parent_id: parentId },
    }),
  });
  branchId = created.branch?.id ?? created.id;
  console.log(`Created branch: ${branchId}`);
}

const connResp = await api(
  `/projects/${projectId}/connection_uri?branch_id=${branchId}&role_name=neondb_owner&database_name=neondb`,
);
const connectionUri = connResp.uri ?? connResp.connection_uri;
if (!connectionUri) {
  console.log(JSON.stringify(connResp, null, 2));
  throw new Error("Could not resolve staging connection URI — copy from Neon Console → branch staging");
}

const stagingAuthSecret = randomBytes(32).toString("base64url");
const outPath = join(root, ".env.staging.local");
const lines = [
  "# Generated by setup-neon-staging-branch.mjs — DO NOT COMMIT",
  `DATABASE_URL=${connectionUri}`,
  `DATABASE_URL_DIRECT=${connectionUri}`,
  `AUTH_SECRET=${stagingAuthSecret}`,
  "AUTH_URL=https://staging.seps.fazagroup.id",
  "PORT=8080",
  "VITE_DATA_BACKEND=neon",
  "VITE_APP_NAME=SEPS Staging",
  "VITE_APP_ENV=staging",
  "VITE_PUBLIC_APP_URL=https://staging.seps.fazagroup.id",
  "NODE_ENV=production",
  "",
];

writeFileSync(outPath, lines.join("\n"), "utf8");

console.log(`
OK — staging branch ready.

Next:
1. Copy variables to Railway STAGING service (Raw Editor):
   ${outPath}

2. Run migrations against staging:
   set DATABASE_URL from .env.staging.local, then:
   npm run neon:migrate
   npm run neon:uat:sync

3. Railway → New service → branch "staging" → deploy
4. DNS CNAME staging.seps → Railway staging target
`);
